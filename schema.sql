-- Esquema para tienda online en PostgreSQL / Supabase

CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    descripcion TEXT,
    precio NUMERIC(10, 2) NOT NULL CHECK (precio > 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    categoria TEXT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    ciudad TEXT NOT NULL
);

CREATE TABLE cupones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL UNIQUE,
    porcentaje INTEGER NOT NULL CHECK (porcentaje BETWEEN 1 AND 100),
    vigente_hasta DATE NOT NULL,
    usos_maximos INTEGER NOT NULL CHECK (usos_maximos > 0)
);

CREATE TABLE cupon_usos (
    cupon_id BIGINT NOT NULL REFERENCES cupones(id),
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    PRIMARY KEY (cupon_id, cliente_id)
);

CREATE TABLE tarifas_envio (
    ciudad TEXT PRIMARY KEY,
    costo NUMERIC(10, 2) NOT NULL CHECK (costo >= 0)
);

CREATE TABLE ordenes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    cupon_id BIGINT REFERENCES cupones(id),
    estado TEXT NOT NULL DEFAULT 'nueva'
        CHECK (estado IN ('nueva', 'pagada', 'enviada', 'entregada', 'cancelada')),
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
    descuento NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (descuento >= 0),
    envio NUMERIC(10, 2) NOT NULL CHECK (envio >= 0),
    total NUMERIC(10, 2) NOT NULL CHECK (total >= 0)
);

CREATE TABLE orden_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id BIGINT NOT NULL REFERENCES ordenes(id) ON DELETE CASCADE,
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10, 2) NOT NULL CHECK (precio_unitario > 0),
    producto_nombre TEXT NOT NULL,
    categoria TEXT NOT NULL
);

